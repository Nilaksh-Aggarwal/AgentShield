using System.Globalization;
using System.Text;
using AgentShield.Evaluation.Dataset;
using AgentShield.Evaluation.Hosting;
using AgentShield.Evaluation.Report;
using AgentShield.Evaluation.Results;

namespace AgentShield.Evaluation.Reliability;

/// <summary>
/// tests/Evaluation/reliability/results/report.md: baseline against final on the same fixtures, per set, category and
/// language, with the number of inputs behind every rate, and any real-Gemini run of a held-out set kept apart from the
/// deterministic results. Built from the stored runs only.
/// </summary>
internal static class ReliabilityReport
{
    public const string FileName = "report.md";

    public static string Build() => Build(Paths.DefaultResults);

    /// <param name="aiResults">The AI evaluation results directory, whose <c>reliability-*</c> folders hold real-Gemini runs.</param>
    public static string Build(string aiResults)
    {
        var text = new StringBuilder();
        text.AppendLine("# Reliability evaluation");
        text.AppendLine();
        text.AppendLine("Generated by `dotnet run --project tests/AgentShield.Evaluation -- reliability-report` from the stored runs. Three kinds");
        text.AppendLine("of result are kept apart and never combined:");
        text.AppendLine();
        text.AppendLine("- **Deterministic (AI off):** provider cap 0; no AI involved.");
        text.AppendLine("- **Simulated AI outage:** AI on, a fake transport answering HTTP 503, no network request.");
        text.AppendLine("- **Real Gemini:** only where a section says so, from `tests/Evaluation/results/reliability-<set>` (the AI");
        text.AppendLine("  evaluation runner, ADR 0017), with the model and the number of completed analyses it rests on.");
        text.AppendLine();
        text.AppendLine("A positive is an input labelled Block; it counts as detected when the decision is not Allow (Review or Block), and a");
        text.AppendLine("benign input counts as a false positive on the same terms. Rates are given with their counts.");
        text.AppendLine();

        foreach (var split in ReliabilityDataset.Available())
        {
            var baseline = ReliabilityRunner.LoadRun(ReliabilityRunner.RunFile("baseline", split, ReliabilityMode.Deterministic));
            var final = ReliabilityRunner.LoadRun(ReliabilityRunner.RunFile("final", split, ReliabilityMode.Deterministic));
            if (baseline is null && final is null)
            {
                continue;
            }

            var dataset = ReliabilityDataset.Load(split);
            var reference = final ?? baseline!;
            text.AppendLine(Invariant($"## {Title(split, dataset)}"));
            text.AppendLine();
            text.AppendLine(Invariant($"Dataset fingerprint `{reference.DatasetFingerprint}`, {reference.Outcomes.Count} inputs ({reference.Outcomes.Count(o => o.Label != Labels.Allow)} positive, {reference.Outcomes.Count(o => o.Label == Labels.Allow)} benign)."));
            if (dataset.ContentFingerprint() != reference.DatasetFingerprint)
            {
                text.AppendLine();
                text.AppendLine("**The stored runs were made with different dataset contents than the file now holds; re-run them.**");
            }

            if (baseline is not null && final is not null && baseline.DatasetFingerprint != final.DatasetFingerprint)
            {
                text.AppendLine();
                text.AppendLine("**The baseline and final runs used different dataset contents; they are not comparable.**");
            }

            text.AppendLine();
            text.AppendLine("| Deterministic (AI off) | TP | FN | FP | TN | Errors | Precision | Recall | False-negative rate | False-positive rate |");
            text.AppendLine("|---|---|---|---|---|---|---|---|---|---|");
            foreach (var (name, run) in new[] { ("Baseline", baseline), ("Final", final) })
            {
                if (run is null)
                {
                    continue;
                }

                var c = Confusion.Of(run.Outcomes);
                text.AppendLine(Invariant($"| {name} ({run.RanAt:yyyy-MM-dd HH:mm} UTC) | {c.TruePositives} | {c.FalseNegatives} | {c.FalsePositives} | {c.TrueNegatives} | {c.Errors} | {Rate(c.Precision, c.TruePositives, c.TruePositives + c.FalsePositives)} | {Rate(c.Recall, c.TruePositives, c.Positives)} | {Rate(c.Positives == 0 ? null : (double)c.FalseNegatives / c.Positives, c.FalseNegatives, c.Positives)} | {Rate(c.FalsePositiveRate, c.FalsePositives, c.Negatives)} |"));
            }

            text.AppendLine();
            text.AppendLine("| Category | Inputs | Baseline | Final |");
            text.AppendLine("|---|---|---|---|");
            foreach (var category in reference.Outcomes.Select(o => o.Category).Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal))
            {
                var inputs = reference.Outcomes.Where(o => o.Category == category).ToList();
                text.AppendLine(Invariant($"| {category} | {inputs.Count} | {Group(baseline, o => o.Category == category)} | {Group(final, o => o.Category == category)} |"));
            }

            text.AppendLine();
            var languages = dataset.Fixtures.Where(fixture => fixture.Language is not null)
                .ToDictionary(fixture => fixture.Id, fixture => fixture.Language!, StringComparer.Ordinal);
            if (languages.Count > 0)
            {
                text.AppendLine("| Language | Inputs (positive / benign) | Baseline | Final |");
                text.AppendLine("|---|---|---|---|");
                foreach (var language in languages.Values.Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal))
                {
                    bool InLanguage(ReliabilityOutcome outcome) => languages.GetValueOrDefault(outcome.Id) == language;
                    var inputs = reference.Outcomes.Where(InLanguage).ToList();
                    text.AppendLine(Invariant($"| {language} | {inputs.Count} ({inputs.Count(o => o.Label != Labels.Allow)} / {inputs.Count(o => o.Label == Labels.Allow)}) | {Group(baseline, InLanguage)} | {Group(final, InLanguage)} |"));
                }

                text.AppendLine();
            }

            if (final is not null)
            {
                var missed = final.Outcomes.Where(o => o.Status == 200 && o.Label != Labels.Allow && !o.Detected).Select(o => o.Id).ToList();
                var falseAlarms = final.Outcomes.Where(o => o.Status == 200 && o.Label == Labels.Allow && o.Detected).Select(o => o.Id).ToList();
                text.AppendLine(Invariant($"Final misses ({missed.Count}): {(missed.Count == 0 ? "none" : string.Join(", ", missed))}."));
                text.AppendLine();
                text.AppendLine(Invariant($"Final false positives ({falseAlarms.Count}): {(falseAlarms.Count == 0 ? "none" : string.Join(", ", falseAlarms))}."));
                text.AppendLine();
            }

            var unavailable = ReliabilityRunner.LoadRun(ReliabilityRunner.RunFile("final", split, ReliabilityMode.AiUnavailable));
            if (unavailable is not null)
            {
                var decisions = unavailable.Outcomes.GroupBy(o => o.Decision ?? "error").ToDictionary(g => g.Key, g => g.Count(), StringComparer.Ordinal);
                text.AppendLine(Invariant($"Simulated AI outage (AI on, {unavailable.SimulatedProviderResponses} simulated provider responses, 0 network requests): Allow {decisions.GetValueOrDefault("Allow")}, Review {decisions.GetValueOrDefault("Review")}, Block {decisions.GetValueOrDefault("Block")}, errors {decisions.GetValueOrDefault("error")}. Every input the rules do not block is held for review; none is allowed."));
                text.AppendLine();
            }

            if (ReliabilityDataset.IsHeldOut(split))
            {
                RealGemini(text, dataset, final, ReliabilityRunner.RealRunDirectory(aiResults, split));
            }

            if (ReliabilityDataset.Retired.TryGetValue(split, out var retiredAt))
            {
                var store = ReliabilityRunner.RealRunDirectory(aiResults, split);
                var sessions = Directory.Exists(store) ? new ResultStore(store).LoadSessions().Where(session => session.Mode == "Real").ToList() : [];
                var after = sessions.Count(session => DateTimeOffset.Parse(session.StartedUtc, CultureInfo.InvariantCulture) >= retiredAt);
                text.AppendLine(Invariant($"**Retired to development data at {retiredAt:yyyy-MM-dd HH:mm:ss} UTC (ADR 0027).** The deterministic \"Final\" row above and every later run on this set are development numbers, not held-out evidence. The held-out evidence is frozen in `results/{Path.GetFileName(ReliabilityDataset.FrozenEvidenceDirectory(split))}` (deterministic baseline and final, simulated outage, and the report as it stood) and in the real-Gemini sessions above that started before the retirement ({sessions.Count - after} of {sessions.Count}{(after > 0 ? Invariant($"; {after} started later and are development numbers") : string.Empty)})."));
                text.AppendLine();
            }
        }

        return text.ToString();
    }

    /// <summary>
    /// The real-Gemini section of a held-out set: final decisions of the fixtures the runner sent, how many AI analyses
    /// completed, which model, and whether the rules have changed since (then the run describes older rules).
    /// </summary>
    private static void RealGemini(StringBuilder text, ReliabilityDataset dataset, ReliabilityRun? final, string directory)
    {
        var store = Directory.Exists(directory) ? new ResultStore(directory) : null;
        var sessions = store?.LoadSessions() ?? [];
        var realSessions = sessions.Where(session => session.Mode == "Real").ToList();
        text.AppendLine("### AI on, real Gemini");
        text.AppendLine();
        if (realSessions.Count == 0)
        {
            text.AppendLine(Invariant($"**No real-Gemini run of this set exists.** AI-assisted accuracy on it is not measured. (Results would be in `tests/Evaluation/results/{Path.GetFileName(directory)}`.)"));
            text.AppendLine();
            return;
        }

        var baseline = store!.LoadBaseline();
        var attempts = store.LoadAttempts().Where(attempt => realSessions.Exists(session => session.SessionId == attempt.SessionId)).ToList();
        var metrics = EvaluationMetrics.Compute(dataset.ToEvaluationDataset(), baseline, attempts);
        var models = realSessions.Select(session => session.Configuration.GetValueOrDefault("Ai:Model") ?? "unknown").Distinct(StringComparer.Ordinal);
        var sent = metrics.Fixtures.Where(result => result.FinalDecision is not null).ToList();
        var c = Confusion.Of(sent.Select(result => new ReliabilityOutcome(result.Fixture.Id, result.Fixture.Category, result.Fixture.Label, 200, result.FinalDecision, [], result.Outcome!.AiStatus)));
        var failed = sent.Count(result => result.AiFailed);

        text.AppendLine(Invariant($"Model {string.Join(", ", models)}; {realSessions.Count} real session(s), {realSessions.Sum(s => s.ProviderCalls)} provider calls, {realSessions.Min(s => s.StartedUtc)} to {realSessions.Max(s => s.FinishedUtc)} UTC; committed capacity, circuit breaker and 3 s timeout."));
        text.AppendLine();
        text.AppendLine(Invariant($"- Coverage: **{sent.Count} of {dataset.Fixtures.Count}** fixtures have a final decision; **{metrics.AiCompleted} of {metrics.AiEvaluable}** fixtures that need the AI have a completed AI analysis; {failed} AI analyses failed and were held for review (fail closed); deterministic Blocks skip the AI by design."));
        var unrecorded = store.SentWithoutResult();
        text.AppendLine(Invariant($"- Sent without a recorded result (the process ended mid-call; never sent again): {unrecorded.Count}. Send records exist for sessions run since the write-ahead guard (2026-10-09); earlier sessions are reconciled by their call counts."));
        if (final is not null)
        {
            var current = final.Outcomes.ToDictionary(outcome => outcome.Id, outcome => outcome.Decision, StringComparer.Ordinal);
            var changed = baseline.Count(record => current.GetValueOrDefault(record.FixtureId) != record.Decision);
            text.AppendLine(changed == 0
                ? "- The deterministic decisions the run started from equal the current final deterministic run."
                : Invariant($"- **The rules changed since this run:** {changed} deterministic decisions differ from the current final run, so these results describe the earlier rules."));
        }

        if (sent.Count < dataset.Fixtures.Count)
        {
            text.AppendLine(Invariant($"- **Incomplete:** the figures below rest on the {sent.Count} fixtures with a final decision only and must not be quoted for the whole set."));
        }
        else if (failed > 0)
        {
            text.AppendLine(Invariant($"- **Every fixture has a final decision.** The first row is the AI-on configuration as it ran, including {failed} decisions that came from failed AI analyses (held for review). The second row leaves those out: it describes the completed analyses, not the configuration."));
        }

        text.AppendLine();
        text.AppendLine("| Final decision (AI on, real Gemini) | TP | FN | FP | TN | Precision | Recall | False-negative rate | False-positive rate |");
        text.AppendLine("|---|---|---|---|---|---|---|---|---|");
        ConfusionRow(text, Invariant($"{sent.Count} fixtures with a final decision"), c);
        if (failed > 0)
        {
            var completed = sent.Where(result => !result.AiFailed).ToList();
            ConfusionRow(text, Invariant($"{completed.Count} without a failed AI analysis"), Confusion.Of(completed.Select(result => new ReliabilityOutcome(result.Fixture.Id, result.Fixture.Category, result.Fixture.Label, 200, result.FinalDecision, [], result.Outcome!.AiStatus))));
        }
        text.AppendLine();
        text.AppendLine("| Category | Sent | Final: detected / allowed |");
        text.AppendLine("|---|---|---|");
        foreach (var group in sent.GroupBy(result => result.Fixture.Category, StringComparer.Ordinal).OrderBy(group => group.Key, StringComparer.Ordinal))
        {
            var positive = group.All(result => result.Fixture.Positive);
            var correct = group.Count(result => (result.FinalDecision != Labels.Allow) == result.Fixture.Positive);
            text.AppendLine(Invariant($"| {group.Key} | {group.Count()} | {(positive ? "detected" : "allowed")} {correct}/{group.Count()} |"));
        }

        text.AppendLine();
        text.AppendLine("| Decided by | Fixtures |");
        text.AppendLine("|---|---|");
        foreach (var group in sent.GroupBy(result => result.DecidedBy ?? "not sent", StringComparer.Ordinal).OrderBy(group => group.Key, StringComparer.Ordinal))
        {
            text.AppendLine(Invariant($"| {group.Key} | {group.Count()} |"));
        }

        var misses = sent.Where(result => result.Fixture.Positive && result.FinalDecision == Labels.Allow).Select(result => result.Fixture.Id).ToList();
        var falseAlarms = sent.Where(result => !result.Fixture.Positive && result.FinalDecision != Labels.Allow).Select(result => result.Fixture.Id).ToList();
        text.AppendLine();
        text.AppendLine(Invariant($"Misses with AI on ({misses.Count}): {(misses.Count == 0 ? "none" : string.Join(", ", misses))}."));
        text.AppendLine();
        text.AppendLine(Invariant($"False positives with AI on ({falseAlarms.Count}): {(falseAlarms.Count == 0 ? "none" : string.Join(", ", falseAlarms))}."));
        text.AppendLine();
    }

    private static void ConfusionRow(StringBuilder text, string name, Confusion c) =>
        text.AppendLine(Invariant($"| {name} | {c.TruePositives} | {c.FalseNegatives} | {c.FalsePositives} | {c.TrueNegatives} | {Rate(c.Precision, c.TruePositives, c.TruePositives + c.FalsePositives)} | {Rate(c.Recall, c.TruePositives, c.Positives)} | {Rate(c.Positives == 0 ? null : (double)c.FalseNegatives / c.Positives, c.FalseNegatives, c.Positives)} | {Rate(c.FalsePositiveRate, c.FalsePositives, c.Negatives)} |"));

    private static string Title(string split, ReliabilityDataset dataset) => split switch
    {
        ReliabilityDataset.HeldOut => ReliabilityDataset.Retired.ContainsKey(split)
            ? "Held-out set v1 (written before the 2026-10-09 rule changes; retired to development data, see below)"
            : "Held-out set v1 (written before the 2026-10-09 rule changes; never tuned against)",
        ReliabilityDataset.Tuning => "Tuning set v1 (the rules were developed against it: not evidence of generalisation)",
        ReliabilityDataset.Legacy => "Legacy AI evaluation set v1 (113 inputs, 2026-09-30; not tuned against)",
        _ when ReliabilityDataset.IsHeldOut(split) => Invariant($"Held-out set v{dataset.Version} (`{split}`; pinned before measurement; never tuned against)"),
        _ => Invariant($"Tuning set v{dataset.Version} (`{split}`; development data: not evidence of generalisation)"),
    };

    // All positive: "detected"; all benign: "allowed"; mixed labels (some legacy categories hold Review-labelled
    // inputs, and a language holds both): "correct", i.e. positives not allowed and benign inputs allowed.
    private static string Group(ReliabilityRun? run, Func<ReliabilityOutcome, bool> member)
    {
        if (run is null)
        {
            return "—";
        }

        var inputs = run.Outcomes.Where(member).ToList();
        var correct = inputs.Count(o => o.Status == 200 && o.Detected == (o.Label != Labels.Allow));
        var word = inputs.All(o => o.Label != Labels.Allow) ? "detected" : inputs.All(o => o.Label == Labels.Allow) ? "allowed" : "correct";
        return Invariant($"{word} {correct}/{inputs.Count}");
    }

    private static string Rate(double? value, int numerator, int denominator) =>
        value is null ? "n/a" : Invariant($"{value.Value:0.000} ({numerator}/{denominator})");

    private static string Invariant(FormattableString value) => value.ToString(CultureInfo.InvariantCulture);
}
