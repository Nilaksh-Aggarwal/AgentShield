using System.Globalization;
using System.Text;

namespace AgentShield.Evaluation.Reliability;

/// <summary>
/// tests/Evaluation/reliability/results/report.md: baseline against final on the same fixtures, per set and per category,
/// with the number of inputs behind every rate. Built from the stored runs only.
/// </summary>
internal static class ReliabilityReport
{
    public const string FileName = "report.md";

    private static readonly string[] Splits = [ReliabilityDataset.HeldOut, ReliabilityDataset.Tuning, ReliabilityDataset.Legacy];

    public static string Build()
    {
        var text = new StringBuilder();
        text.AppendLine("# Reliability evaluation");
        text.AppendLine();
        text.AppendLine("Generated by `dotnet run --project tests/AgentShield.Evaluation -- reliability-report` from the stored runs in this");
        text.AppendLine("folder. **No run here called Gemini:** deterministic runs have AI off (provider cap 0); `ai-unavailable` runs have AI");
        text.AppendLine("on with a simulated provider outage (HTTP 503 from a fake transport, no network). A positive is an input labelled");
        text.AppendLine("Block or Review; it counts as detected when the decision is not Allow. Rates are given with their counts.");
        text.AppendLine();

        foreach (var split in Splits)
        {
            var baseline = ReliabilityRunner.LoadRun(ReliabilityRunner.RunFile("baseline", split, ReliabilityMode.Deterministic));
            var final = ReliabilityRunner.LoadRun(ReliabilityRunner.RunFile("final", split, ReliabilityMode.Deterministic));
            if (baseline is null && final is null)
            {
                continue;
            }

            var reference = final ?? baseline!;
            text.AppendLine(Invariant($"## {Title(split)}"));
            text.AppendLine();
            text.AppendLine(Invariant($"Dataset fingerprint `{reference.DatasetFingerprint}`, {reference.Outcomes.Count} inputs ({reference.Outcomes.Count(o => o.Label != "Allow")} positive, {reference.Outcomes.Count(o => o.Label == "Allow")} benign)."));
            if (baseline is not null && final is not null && baseline.DatasetFingerprint != final.DatasetFingerprint)
            {
                text.AppendLine();
                text.AppendLine("**The baseline and final runs used different dataset contents; they are not comparable.**");
            }

            text.AppendLine();
            text.AppendLine("| Deterministic (AI off) | TP | FN | FP | TN | Errors | Precision | Recall | False-positive rate |");
            text.AppendLine("|---|---|---|---|---|---|---|---|---|");
            foreach (var (name, run) in new[] { ("Baseline", baseline), ("Final", final) })
            {
                if (run is null)
                {
                    continue;
                }

                var c = Confusion.Of(run.Outcomes);
                text.AppendLine(Invariant($"| {name} ({run.RanAt:yyyy-MM-dd HH:mm} UTC) | {c.TruePositives} | {c.FalseNegatives} | {c.FalsePositives} | {c.TrueNegatives} | {c.Errors} | {Rate(c.Precision, c.TruePositives, c.TruePositives + c.FalsePositives)} | {Rate(c.Recall, c.TruePositives, c.Positives)} | {Rate(c.FalsePositiveRate, c.FalsePositives, c.Negatives)} |"));
            }

            text.AppendLine();
            text.AppendLine("| Category | Inputs | Baseline | Final |");
            text.AppendLine("|---|---|---|---|");
            foreach (var category in reference.Outcomes.Select(o => o.Category).Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal))
            {
                var inputs = reference.Outcomes.Where(o => o.Category == category).ToList();
                text.AppendLine(Invariant($"| {category} | {inputs.Count} | {Category(baseline, category)} | {Category(final, category)} |"));
            }

            text.AppendLine();
            if (final is not null)
            {
                var missed = final.Outcomes.Where(o => o.Status == 200 && o.Label != "Allow" && !o.Detected).Select(o => o.Id).ToList();
                var falseAlarms = final.Outcomes.Where(o => o.Status == 200 && o.Label == "Allow" && o.Detected).Select(o => o.Id).ToList();
                text.AppendLine(Invariant($"Final misses ({missed.Count}): {(missed.Count == 0 ? "none" : string.Join(", ", missed))}."));
                text.AppendLine();
                text.AppendLine(Invariant($"Final false positives ({falseAlarms.Count}): {(falseAlarms.Count == 0 ? "none" : string.Join(", ", falseAlarms))}."));
                text.AppendLine();
            }

            var unavailable = ReliabilityRunner.LoadRun(ReliabilityRunner.RunFile("final", split, ReliabilityMode.AiUnavailable));
            if (unavailable is not null)
            {
                var decisions = unavailable.Outcomes.GroupBy(o => o.Decision ?? "error").ToDictionary(g => g.Key, g => g.Count(), StringComparer.Ordinal);
                text.AppendLine(Invariant($"AI on, provider unavailable (simulated, {unavailable.SimulatedProviderResponses} simulated provider responses, 0 network requests): Allow {decisions.GetValueOrDefault("Allow")}, Review {decisions.GetValueOrDefault("Review")}, Block {decisions.GetValueOrDefault("Block")}, errors {decisions.GetValueOrDefault("error")}. Every input the rules do not block is held for review; none is allowed."));
                text.AppendLine();
            }
        }

        return text.ToString();
    }

    private static string Title(string split) => split switch
    {
        ReliabilityDataset.HeldOut => "Held-out set (written before any rule change; never tuned against)",
        ReliabilityDataset.Tuning => "Tuning set (the rules were developed against it: not evidence of generalisation)",
        _ => "Legacy AI evaluation set v1 (113 inputs, 2026-09-30; not tuned against)",
    };

    // All positive: "detected"; all benign: "allowed"; mixed labels (some legacy categories hold Review-labelled
    // inputs): "correct", i.e. positives not allowed and benign inputs allowed.
    private static string Category(ReliabilityRun? run, string category)
    {
        if (run is null)
        {
            return "—";
        }

        var inputs = run.Outcomes.Where(o => o.Category == category).ToList();
        var correct = inputs.Count(o => o.Status == 200 && o.Detected == (o.Label != "Allow"));
        var word = inputs.All(o => o.Label != "Allow") ? "detected" : inputs.All(o => o.Label == "Allow") ? "allowed" : "correct";
        return Invariant($"{word} {correct}/{inputs.Count}");
    }

    private static string Rate(double? value, int numerator, int denominator) =>
        value is null ? "n/a" : Invariant($"{value.Value:0.000} ({numerator}/{denominator})");

    private static string Invariant(FormattableString value) => value.ToString(CultureInfo.InvariantCulture);
}
