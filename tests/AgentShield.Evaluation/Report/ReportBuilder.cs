using System.Globalization;
using System.Text;
using AgentShield.Evaluation.Dataset;
using AgentShield.Evaluation.Results;

namespace AgentShield.Evaluation.Report;

/// <summary>
/// The evaluation report (Markdown): fixture IDs, codes, statuses, numbers and the dataset's own label rationales only.
/// Every AI figure states how many completed analyses it rests on; nothing is extrapolated.
/// </summary>
internal static class ReportBuilder
{
    private static readonly string[] SeverityOrder = ["Low", "Medium", "High", "Critical"];

    /// <summary>Paths whose fixtures are listed by ID; the bulk paths are in the per-fixture table only.</summary>
    private const int MaxListedFixtures = 20;

    public static string Build(EvaluationDataset dataset, IReadOnlyList<BaselineRecord> baseline, IReadOnlyList<AttemptRecord> attempts, IReadOnlyList<SessionRecord> sessions)
    {
        ArgumentNullException.ThrowIfNull(dataset);
        ArgumentNullException.ThrowIfNull(sessions);

        var metrics = EvaluationMetrics.Compute(dataset, baseline, attempts);
        var text = new StringBuilder();
        void Line(string line = "") => text.Append(line).Append('\n');

        Line(Invariant($"# AI security evaluation: dataset v{dataset.Version}"));
        Line();
        Line("Generated by `tests/AgentShield.Evaluation` from the results store. Fixture IDs, codes, statuses and numbers only: no input, prompt, provider answer or model-written text.");
        Line();
        Line(Invariant($"- Dataset: {dataset.Fixtures.Count} synthetic fixtures (Block {Labelled(dataset, Labels.Block)}, Review {Labelled(dataset, Labels.Review)}, Allow {Labelled(dataset, Labels.Allow)}); input fingerprint (texts) `{dataset.InputFingerprint()[..16]}`, content fingerprint (texts, labels, expectations) `{dataset.ContentFingerprint()[..16]}`. Stored attempts are scored with the labels of this version."));
        Line(Invariant($"- Deterministic baseline (AI off): all {metrics.Fixtures.Count} fixtures; fingerprint `{ResultStore.Fingerprint(baseline)[..16]}`."));
        Line(Invariant($"- AI coverage: **{metrics.AiCompleted} of {metrics.AiEvaluable}** fixtures the production configuration sends to the AI have a completed AI analysis ({Percent(metrics.AiCompleted, metrics.AiEvaluable)}); {metrics.NotRun} fixtures have not been sent successfully yet."));
        if (metrics.AiCompleted < metrics.AiEvaluable)
        {
            Line();
            Line(Invariant($"> **Incomplete AI evaluation.** AI figures describe only the {metrics.AiCompleted} completed analyses. They are not an estimate for the whole set and must not be quoted as the model's accuracy."));
        }

        Line();
        Line("## Sessions");
        Line();
        if (sessions.Count == 0)
        {
            Line("No session has run.");
        }
        else
        {
            Line("| Session | Mode | Subset | Duration (s) | Planned | Sent | Provider calls (cap) | Stop | Leak hits | Note |");
            Line("|---|---|---|---:|---:|---:|---:|---|---:|---|");
            foreach (var session in sessions)
            {
                Line(Invariant($"| {session.SessionId} | {session.Mode} | {session.Subset}{(session.ExcludeFailed ? ", failed excluded" : string.Empty)} | {Seconds(session)} | {session.PlannedFixtures} | {session.FixturesSent} | {session.ProviderCalls} ({session.MaxCalls}) | {session.StopReason} | {session.LeakHits} | {session.Note} |"));
            }

            Line();
            Line(Invariant($"{sessions.Count} sessions, {sessions.Sum(s => s.ProviderCalls)} provider calls, {sessions.Sum(s => s.FixturesSent)} fixtures sent; time inside sessions {sessions.Sum(s => DurationSeconds(s) ?? 0):F0} s (pauses between sessions not included)."));
        }

        Line();
        Line("## Detection: deterministic vs AI");
        Line();
        Line("Positives: fixtures labelled Block or Review. Flagged: at least one finding (deterministic: baseline with AI off; AI: an `*.AiDetected` finding in a completed analysis). Intervals are 95 % Wilson score intervals; with few analyses they are wide.");
        Line();
        Line("| | Deterministic | AI |");
        Line("|---|---:|---:|");
        Line(Invariant($"| Fixtures evaluated | {metrics.Deterministic.Evaluated} | {metrics.Ai.Evaluated} |"));
        Line(Invariant($"| True positives | {metrics.Deterministic.TruePositives} | {metrics.Ai.TruePositives} |"));
        Line(Invariant($"| False positives | {metrics.Deterministic.FalsePositives} | {metrics.Ai.FalsePositives} |"));
        Line(Invariant($"| False negatives (misses) | {metrics.Deterministic.FalseNegatives} | {metrics.Ai.FalseNegatives} |"));
        Line(Invariant($"| True negatives | {metrics.Deterministic.TrueNegatives} | {metrics.Ai.TrueNegatives} |"));
        Line(Invariant($"| Precision | {Rate(metrics.Deterministic.TruePositives, metrics.Deterministic.TruePositives + metrics.Deterministic.FalsePositives)} | {Rate(metrics.Ai.TruePositives, metrics.Ai.TruePositives + metrics.Ai.FalsePositives)} |"));
        Line(Invariant($"| Recall | {Rate(metrics.Deterministic.TruePositives, metrics.Deterministic.TruePositives + metrics.Deterministic.FalseNegatives)} | {Rate(metrics.Ai.TruePositives, metrics.Ai.TruePositives + metrics.Ai.FalseNegatives)} |"));
        Line(Invariant($"| AI-only detections (AI flagged, deterministic did not) | - | {metrics.AiOnlyDetections.Count} |"));
        Line();
        FixtureList("AI-only detections", metrics.AiOnlyDetections, result => Findings(result.Outcome!.AiFindings));
        FixtureList("AI misses (positive, completed, no AI finding)", metrics.AiMisses, result =>
            Invariant($"{result.Fixture.CategoryName}; {result.Fixture.Language}; obfuscation {result.Fixture.Obfuscation}; deterministic {(result.DeterministicFlag ? Findings(result.Baseline.Findings) : "none")}; final {result.FinalDecision}; cause unknown"));
        FixtureList("AI false positives (benign, AI finding)", metrics.AiFalsePositives, result =>
            Invariant($"{result.Fixture.CategoryName}; {Findings(result.Outcome!.AiFindings)}; deterministic {(result.DeterministicFlag ? Findings(result.Baseline.Findings) : "none")}; final {result.FinalDecision}; label rationale: {result.Fixture.Rationale}"));

        FinalDecisions(metrics);

        Line("## Decision changes (deterministic → final)");
        Line();
        Line("| Deterministic \\ Final | Allow | Review | Block | not sent yet |");
        Line("|---|---:|---:|---:|---:|");
        foreach (var from in EvaluationMetrics.Decisions)
        {
            Line(Invariant($"| {from} | {metrics.Transitions[(from, Labels.Allow)]} | {metrics.Transitions[(from, Labels.Review)]} | {metrics.Transitions[(from, Labels.Block)]} | {metrics.Fixtures.Count(r => r.Baseline.Decision == from && r.FinalDecision is null)} |"));
        }

        Line();
        Line(Invariant($"Block → Block {metrics.Transitions[(Labels.Block, Labels.Block)]}; Allow → Allow {metrics.Transitions[(Labels.Allow, Labels.Allow)]}; Allow → Block {metrics.Transitions[(Labels.Allow, Labels.Block)]}; Allow → Review {metrics.Transitions[(Labels.Allow, Labels.Review)]}; Review → Block {metrics.Transitions[(Labels.Review, Labels.Block)]}; Review → Review {metrics.Transitions[(Labels.Review, Labels.Review)]}; **Block → anything else {metrics.Transitions[(Labels.Block, Labels.Allow)] + metrics.Transitions[(Labels.Block, Labels.Review)]}**; Review → Allow {metrics.Transitions[(Labels.Review, Labels.Allow)]}."));
        Line();

        var outcomes = metrics.Outcomes;
        Line("## Attempts, failures and latency");
        Line();
        Line(Invariant($"Every attempt ever made, failures included: {outcomes.Attempts} attempts, {outcomes.ProviderCalls} provider calls."));
        Line();
        Line("| Outcome | Attempts |");
        Line("|---|---:|");
        Line(Invariant($"| Completed | {outcomes.Completed} |"));
        Line(Invariant($"| Not needed (deterministic Block, no provider call) | {outcomes.NotNeeded} |"));
        Line(Invariant($"| **Timed out** | {outcomes.TimedOut} |"));
        Line(Invariant($"| **Provider failures** (429 {outcomes.RateLimited}, 5xx/unavailable {outcomes.Unavailable}, network {outcomes.NetworkFailures}) | {outcomes.ProviderFailures} |"));
        Line(Invariant($"| **Contract-validation failures** (malformed {outcomes.MalformedResponses}, invalid {outcomes.InvalidResponses}) | {outcomes.ContractValidationFailures} |"));
        Line(Invariant($"| Refused by the model | {outcomes.Refused} |"));
        Line(Invariant($"| Capacity exceeded / circuit open | {outcomes.CapacityExceeded} / {outcomes.CircuitOpen} |"));
        Line(Invariant($"| Other | {outcomes.Other} |"));
        Line();
        Line(Invariant($"Percentiles use the nearest rank; the median needs at least {LatencyStats.MinimumForMedian} values and P95 at least {LatencyStats.MinimumForP95} (below that P95 would only repeat the maximum), otherwise n/a. Timed-out stages are cut off at the timeout."));
        Line();
        Line("| Latency (ms) | n | Average | P50 | P95 | Min | Max |");
        Line("|---|---:|---:|---:|---:|---:|---:|");
        Latency("AI stage, completed analyses", metrics.AiStage);
        Latency("Gemini call, HTTP 200", metrics.ProviderCall);
        Latency("Whole analysis (API round trip), completed", metrics.Total);
        Latency("AI stage, timed out", metrics.TimedOutStage);
        Line();

        Breakdown("Attack types", Taxonomy.AttackTags, metrics, attack: true);
        Breakdown("Benign types", Taxonomy.BenignTags, metrics, attack: false);

        DatasetReview(dataset, metrics, baseline, attempts);
        Tokens(metrics);
        Confidence(metrics);
        Integrity(metrics, sessions);

        Line("## Per fixture");
        Line();
        Line("AI required: the deterministic decision is not Block, so the production configuration sends the input to the AI. Gemini called: the counted attempt made a provider call. AI status names the failure category when the AI did not complete.");
        Line();
        Line("| Fixture | Label | Lang | Obfuscation | Deterministic (AI off) | AI required | Attempts | Gemini called | AI status | AI findings | AI stage ms | Final risk | Final | = label | Decided by | Path |");
        Line("|---|---|---|---|---|---|---:|---|---|---|---:|---|---|---|---|---|");
        foreach (var result in metrics.Fixtures)
        {
            var outcome = result.Outcome;
            Line(Invariant($"| {result.Fixture.Id} | {result.Fixture.Label} | {result.Fixture.Language} | {result.Fixture.Obfuscation} | {result.Baseline.Decision}: {(result.DeterministicFlag ? Findings(result.Baseline.Findings) : "-")} | {(result.AiEvaluable ? "yes" : "no")} | {result.Attempts.Count} | {(outcome is null ? "-" : outcome.ProviderCallCount > 0 ? "yes" : "no")} | {string.Join(" → ", result.Attempts.Select(a => a.AiStatus))} | {(outcome is null || outcome.AiFindings.Count == 0 ? "-" : Findings(outcome.AiFindings))} | {(outcome is { ProviderCallAllowed: true } ? Number(outcome.AiStageMs) : "-")} | {(result.FinalDecision is null ? "-" : Invariant($"{outcome!.RiskLevel} {outcome.RiskScore}"))} | {result.FinalDecision ?? "-"} | {(result.FinalDecision is null ? "-" : result.FinalDecision == result.Fixture.Label ? "yes" : "no")} | {result.DecidedBy ?? "not sent yet"} | {result.Attribution ?? "not sent yet"} |"));
        }

        return text.ToString();

        void FinalDecisions(EvaluationMetrics all)
        {
            var decided = all.Decided;
            Line("## Final decisions: AI off vs AI on");
            Line();
            Line("What AgentShield decided, not which layer added a finding. Positives: labelled Block or Review. Flagged: final decision Review or Block (the input was not allowed; this version decides only Allow, Review or Block). AI off: the deterministic baseline. AI on: the counted attempt; a Review caused by an AI failure counts as flagged, because that is what the system does, but it is never credited to the AI (see the path table). The middle column restricts AI off to the fixtures AI on has decided, so those two columns compare the same fixtures.");
            Line();
            if (decided.Count < all.Fixtures.Count)
            {
                Line(Invariant($"> AI on covers {decided.Count} of {all.Fixtures.Count} fixtures: {decided.Count(r => !r.AiEvaluable)} deterministic Blocks (sent first, they cost no AI call) and {decided.Count(r => r.AiEvaluable)} sent to the AI, {all.AiCompleted} of them completed. The other {all.Fixtures.Count - decided.Count} were not sent. This is not a random sample, so the AI-on figures are not an estimate for the whole set: compare the last two columns with each other only, and read the AI's own effect in the path table."));
                Line();
            }

            Confusion[] views = [all.DeterministicDecisions(decidedOnly: false), all.DeterministicDecisions(decidedOnly: true), all.FinalDecisions];
            void Row(string name, Func<Confusion, string> value) => Line("| " + name + " | " + string.Join(" | ", views.Select(value)) + " |");
            Line("| | AI off, all fixtures | AI off, same fixtures as AI on | AI on (final decision) |");
            Line("|---|---:|---:|---:|");
            Row("Fixtures decided", c => Invariant($"{c.Evaluated}"));
            Row("True positives", c => Invariant($"{c.TruePositives}"));
            Row("False positives", c => Invariant($"{c.FalsePositives}"));
            Row("False negatives (allowed attacks)", c => Invariant($"{c.FalseNegatives}"));
            Row("True negatives", c => Invariant($"{c.TrueNegatives}"));
            Row("Precision", c => Rate(c.TruePositives, c.TruePositives + c.FalsePositives));
            Row("Recall", c => Rate(c.TruePositives, c.TruePositives + c.FalseNegatives));
            Row("F1", c => c.F1 is { } f1 ? Invariant($"{f1:0.00}") : "n/a");
            Line("| Attacks: Block / Review / Allow | " + Split(all.Fixtures, r => r.Baseline.Decision, positive: true) + " | " + Split(decided, r => r.Baseline.Decision, positive: true) + " | " + Split(decided, r => r.FinalDecision, positive: true) + " |");
            Line("| Benign: Block / Review / Allow | " + Split(all.Fixtures, r => r.Baseline.Decision, positive: false) + " | " + Split(decided, r => r.Baseline.Decision, positive: false) + " | " + Split(decided, r => r.FinalDecision, positive: false) + " |");
            Line();

            Line("### Where each final decision came from");
            Line();
            Line("Deterministic decision (AI off) × AI outcome × final decision, for every fixture AI on has decided.");
            Line();
            Line("| Path | Attacks | Benign | Fixtures |");
            Line("|---|---:|---:|---|");
            foreach (var path in Attributions.All)
            {
                var group = decided.Where(r => r.Attribution == path).ToList();
                var ids = group.Count == 0 ? "-" : group.Count > MaxListedFixtures ? "see per fixture" : string.Join(", ", group.Select(r => r.Fixture.Id));
                Line(Invariant($"| {path} | {group.Count(r => r.Fixture.Positive)} | {group.Count(r => !r.Fixture.Positive)} | {ids} |"));
            }

            Line();
            Line("### Final outcome by deciding layer");
            Line();
            Line("Every fixture of the set. A deterministic Block or Review stands whatever the AI does (a deterministic Block never reaches the AI); an AI outcome is one a completed AI analysis produced (Allow included); an AI failure gives the fail-safe Review.");
            Line();
            Line("| Decided by | Attacks | Benign | Total |");
            Line("|---|---:|---:|---:|");
            foreach (var layer in DecidingLayers.All)
            {
                var group = all.Fixtures.Where(r => r.DecidedBy == layer).ToList();
                Line(Invariant($"| {layer} | {group.Count(r => r.Fixture.Positive)} | {group.Count(r => !r.Fixture.Positive)} | {group.Count} |"));
            }

            var unsent = all.Fixtures.Where(r => r.DecidedBy is null).ToList();
            Line(Invariant($"| Not sent yet | {unsent.Count(r => r.Fixture.Positive)} | {unsent.Count(r => !r.Fixture.Positive)} | {unsent.Count} |"));
            Line();
            var tries = all.Fixtures.SelectMany(r => r.Attempts).Where(a => a.ApiStatus == 200).ToList();
            var failed = tries.Where(a => EvaluationMetrics.IsAiFailure(a.AiStatus)).ToList();
            var sentToAi = tries.Where(a => a.ProviderCallAllowed).ToList();
            var calls = tries.Where(a => a.ProviderCallCount > 0).ToList();
            Line("### AI failures and what they decided (every attempt)");
            Line();
            Line(Invariant($"- AI failures: {failed.Count} ({(failed.Count == 0 ? "none" : string.Join(", ", failed.GroupBy(a => a.AiStatus).Select(g => Invariant($"{g.Key} {g.Count()}"))))}). Final decision: **Allow {failed.Count(a => a.Decision == Labels.Allow)}** (must be 0), Review {failed.Count(a => a.Decision == Labels.Review)}, Block {failed.Count(a => a.Decision == Labels.Block)}."));
            Line(Invariant($"- AI completion: {sentToAi.Count(a => a.AiStatus == "Completed")} of {sentToAi.Count} attempts the configuration sends to the AI completed ({Percent(sentToAi.Count(a => a.AiStatus == "Completed"), sentToAi.Count)}); Gemini answered HTTP 200 to {calls.Count(a => a.ProviderCall?.HttpStatus == 200)} of {calls.Sum(a => a.ProviderCallCount)} calls."));
            Line(Invariant($"- Circuit breaker: not Closed before {tries.Count(a => a.CircuitBefore is not null and not "Closed")} and after {tries.Count(a => a.CircuitAfter is not null and not "Closed")} attempts; capacity refusals: {tries.Count(a => a.AiStatus == "CapacityExceeded")}."));
            int Http(int status) => calls.Count(a => a.ProviderCall?.HttpStatus == status);
            int Status(string status) => tries.Count(a => a.AiStatus == status);
            Line(Invariant($"- Provider health (every attempt): HTTP 429 {Http(429)}, HTTP 503 {Http(503)}, other 5xx {calls.Count(a => a.ProviderCall?.HttpStatus is >= 500 and not 503)}, HTTP 408 {Http(408)}, timeouts {Status("TimedOut")}, network failures {Status("NetworkFailure")}, malformed {Status("MalformedResponse")}, invalid {Status("InvalidResponse")}, circuit open {Status("CircuitOpen")}, capacity exhausted {Status("CapacityExceeded")}."));
            Line();
        }

        static string Split(IEnumerable<FixtureResult> results, Func<FixtureResult, string?> decision, bool positive)
        {
            var group = results.Where(r => r.Fixture.Positive == positive).ToList();
            return Invariant($"{group.Count(r => decision(r) == Labels.Block)} / {group.Count(r => decision(r) == Labels.Review)} / {group.Count(r => decision(r) == Labels.Allow)}");
        }

        void FixtureList(string title, IReadOnlyList<FixtureResult> results, Func<FixtureResult, string> describe)
        {
            Line(Invariant($"**{title}:** {(results.Count == 0 ? "none" : string.Empty)}"));
            foreach (var result in results)
            {
                Line("- " + result.Fixture.Id + ": " + describe(result));
            }

            Line();
        }

        void Latency(string name, LatencyStats stats) =>
            Line(Invariant($"| {name} | {stats.Count} | {Number(stats.Average)} | {Number(stats.P50)} | {Number(stats.P95)} | {Number(stats.Min)} | {Number(stats.Max)} |"));

        void Breakdown(string title, IReadOnlyList<(string Tag, string Name)> tags, EvaluationMetrics all, bool attack)
        {
            Line("## " + title);
            Line();
            Line(attack
                ? "| Type | n | Deterministic flagged | AI completed | AI flagged | Final Allow / Review / Block | Not sent yet |"
                : "| Type | n | Deterministic false positives | AI completed | AI false positives | Final Allow / Review / Block | Not sent yet |");
            Line("|---|---:|---:|---:|---:|---|---:|");
            foreach (var (tag, name) in tags)
            {
                var group = all.Fixtures.Where(result => result.Fixture.Tags.Contains(tag)).ToList();
                var deterministic = attack ? group.Count(r => r.Fixture.Positive && r.DeterministicFlag) : group.Count(r => !r.Fixture.Positive && r.DeterministicFlag);
                var ai = attack ? group.Count(r => r.Fixture.Positive && r.AiFlag) : group.Count(r => !r.Fixture.Positive && r.AiFlag);
                Line(Invariant($"| {name} | {group.Count} | {deterministic} | {group.Count(r => r.AiCompleted)} | {ai} | {group.Count(r => r.FinalDecision == Labels.Allow)} / {group.Count(r => r.FinalDecision == Labels.Review)} / {group.Count(r => r.FinalDecision == Labels.Block)} | {group.Count(r => r.FinalDecision is null)} |"));
            }

            Line();
            Line(attack
                ? "A fixture can carry several types. Benign fixtures labelled Review (quoted payloads) appear under benign types."
                : "False positives count fixtures labelled Allow only; the two quoted-payload documents labelled Review count as positives.");
            Line();
        }

        void DatasetReview(EvaluationDataset set, EvaluationMetrics all, IReadOnlyList<BaselineRecord> records, IReadOnlyList<AttemptRecord> tries)
        {
            Line("## Dataset review (labels unchanged)");
            Line();
            Line("Fixtures a person should review before the labels are relied on. Details: `docs/evaluation/dataset-label-review.md`.");
            Line();
            Line("**(a) The deterministic detectors block benign-looking text** (label Allow or Review, deterministic decision Block):");
            foreach (var result in all.Fixtures.Where(r => r.Fixture.Label != Labels.Block && r.Baseline.Decision == Labels.Block))
            {
                Line(Invariant($"- {result.Fixture.Id} (label {result.Fixture.Label}): {Findings(result.Baseline.Findings)}"));
            }

            foreach (var (flag, name) in Taxonomy.ReviewFlags)
            {
                Line();
                Line(Invariant($"**({(flag == "ai-expectation-debatable" ? "b" : "c")}) {name}:**"));
                foreach (var fixture in set.Fixtures.Where(f => f.ReviewFlags.Contains(flag)))
                {
                    Line(Invariant($"- {fixture.Id} (label {fixture.Label}, AI finding expected: {(fixture.ExpectAiFinding ? "yes" : "no")}): {fixture.Rationale}"));
                }
            }

            var clear = EvaluationMetrics.Compute(set, records, tries, fixture => !fixture.ReviewFlags.Contains("label-interpretation"));
            Line();
            Line(Invariant($"Sensitivity (the primary figures above use every label): without the {all.Fixtures.Count - clear.Fixtures.Count} interpretation-dependent fixtures, deterministic precision {Rate(clear.Deterministic.TruePositives, clear.Deterministic.TruePositives + clear.Deterministic.FalsePositives)}, recall {Rate(clear.Deterministic.TruePositives, clear.Deterministic.TruePositives + clear.Deterministic.FalseNegatives)}; AI precision {Rate(clear.Ai.TruePositives, clear.Ai.TruePositives + clear.Ai.FalsePositives)}, recall {Rate(clear.Ai.TruePositives, clear.Ai.TruePositives + clear.Ai.FalseNegatives)} ({clear.Ai.Evaluated} completed analyses)."));
            Line();
        }

        void Tokens(EvaluationMetrics all)
        {
            var calls = all.Fixtures.SelectMany(r => r.Attempts).Where(a => a.ProviderCall?.PromptTokens is > 0 && a.EstimatedInputTokens > 0).ToList();
            Line("## Token estimate vs Gemini usage");
            Line();
            if (calls.Count == 0)
            {
                Line("No usage metadata yet.");
                Line();
                return;
            }

            var ratios = calls.Select(a => (double)a.EstimatedInputTokens / a.ProviderCall!.PromptTokens!.Value).Order().ToList();
            Line(Invariant($"{calls.Count} calls with usage metadata. AgentShield estimate / `promptTokenCount`: mean {ratios.Average():F2}, min {ratios[0]:F2}, max {ratios[^1]:F2}; under-estimates: {calls.Count(a => a.EstimatedInputTokens < a.ProviderCall!.PromptTokens)}. `promptTokenCount` mean {calls.Average(a => a.ProviderCall!.PromptTokens!.Value):F0}, `totalTokenCount` mean {calls.Average(a => a.ProviderCall!.TotalTokens ?? 0):F0}, thought tokens reported in {calls.Count(a => a.ProviderCall!.ThoughtTokens is > 0)} calls."));
            Line();
        }

        void Confidence(EvaluationMetrics all)
        {
            var findings = all.Fixtures.Where(r => r.AiCompleted).SelectMany(r => r.Outcome!.AiFindings).ToList();
            Line("## AI confidence");
            Line();
            if (findings.Count == 0)
            {
                Line("No AI findings yet.");
                Line();
                return;
            }

            Line(Invariant($"{findings.Count} AI findings, {findings.Select(f => f.Confidence).Distinct().Count()} distinct values (not a calibrated probability): ")
                + string.Join(", ", findings.GroupBy(f => f.Confidence).OrderByDescending(g => g.Key).Select(g => Invariant($"{g.Key:0.###} × {g.Count()}")))
                + "; severities: " + string.Join(", ", findings.GroupBy(f => f.Severity).OrderBy(g => Array.IndexOf(SeverityOrder, g.Key)).Select(g => Invariant($"{g.Key} × {g.Count()}"))) + ".");
            Line();
        }

        void Integrity(EvaluationMetrics all, IReadOnlyList<SessionRecord> runs)
        {
            var answered = all.Fixtures.SelectMany(r => r.Attempts.Select(a => (Result: r, Attempt: a))).Where(x => x.Attempt.ApiStatus == 200).ToList();
            Line("## Decision integrity (every attempt)");
            Line();
            Line("| # | Property | Applicable | Held | Violations |");
            Line("|---:|---|---:|---:|---|");
            void Check(int number, string property, Func<(FixtureResult Result, AttemptRecord Attempt), bool> applies, Func<(FixtureResult Result, AttemptRecord Attempt), bool> holds)
            {
                var cases = answered.Where(applies).ToList();
                var violations = cases.Where(x => !holds(x)).Select(x => x.Result.Fixture.Id).Distinct().ToList();
                Line(Invariant($"| {number} | {property} | {cases.Count} | {cases.Count - violations.Count} | {(violations.Count == 0 ? "none" : string.Join(", ", violations))} |"));
            }

            Check(1, "AI never removes a deterministic finding", x => x.Result.DeterministicFlag, x => x.Result.Baseline.Findings.All(b => x.Attempt.Findings.Any(f => f.Code == b.Code)));
            Check(2, "AI never lowers a deterministic severity", x => x.Result.DeterministicFlag, x => x.Result.Baseline.Findings.All(b => x.Attempt.Findings.Any(f => f.Code == b.Code && Rank(f.Severity) >= Rank(b.Severity))));
            Check(3, "Deterministic Block remains Block", x => x.Result.Baseline.Decision == Labels.Block, x => x.Attempt.Decision == Labels.Block);
            Check(4, "Deterministic Blocks never reach the provider", x => x.Result.Baseline.Decision == Labels.Block, x => x.Attempt.ProviderCallCount == 0);
            Check(5, "AI-only High/Critical findings follow the policy (Block)", x => x.Attempt.AiFindings.Any(f => Rank(f.Severity) >= 2) && x.Result.Baseline.Findings.All(f => Rank(f.Severity) < 2), x => x.Attempt.Decision == Labels.Block);
            Check(6, "An AI failure never turns Allow into Block (→ Review)", x => EvaluationMetrics.IsAiFailure(x.Attempt.AiStatus) && x.Result.Baseline.Decision == Labels.Allow, x => x.Attempt.Decision == Labels.Review);
            Check(7, "An AI failure never turns a deterministic Block into Allow", x => EvaluationMetrics.IsAiFailure(x.Attempt.AiStatus) && x.Result.Baseline.Decision == Labels.Block, x => x.Attempt.Decision == Labels.Block);
            Check(8, "Circuit Closed before every AI call; an open circuit is never Allow", x => x.Attempt.ProviderCallAllowed, x => x.Attempt.CircuitBefore is null or "Closed" && (x.Attempt.AiStatus != "CircuitOpen" || x.Attempt.Decision != Labels.Allow));
            Check(9, "Capacity exhaustion is never Allow", x => x.Attempt.AiStatus == "CapacityExceeded", x => x.Attempt.Decision != Labels.Allow);
            Check(10, "Decision = policy(findings); answers carry only `findings`", _ => true, x => x.Attempt.Decision == Policy(x.Attempt.Findings) && x.Attempt.ProviderCall?.AnswerHasOnlyFindings != false);
            Check(11, "No model-written description in the response", _ => true, x => !x.Attempt.DescriptionInResponse);
            Line();
            Line(Invariant($"Leak checks: {runs.Sum(s => s.LeakHits)} hits across {runs.Count} sessions (keys, inputs, decoded payloads, prompt, answers, descriptions in logs, log files, responses, error responses, metric tags and attempt records). Error probes echoing input: {runs.Sum(s => s.ErrorProbes.Count(p => p.Echoed))}."));
            Line();
        }
    }

    private static int Labelled(EvaluationDataset dataset, string label) => dataset.Fixtures.Count(fixture => fixture.Label == label);

    private static double? DurationSeconds(SessionRecord session) =>
        DateTimeOffset.TryParse(session.StartedUtc, CultureInfo.InvariantCulture, DateTimeStyles.RoundtripKind, out var start)
        && DateTimeOffset.TryParse(session.FinishedUtc, CultureInfo.InvariantCulture, DateTimeStyles.RoundtripKind, out var end)
            ? (end - start).TotalSeconds
            : null;

    private static string Seconds(SessionRecord session) => Number(DurationSeconds(session));

    private static int Rank(string severity) => Array.IndexOf(SeverityOrder, severity);

    private static string Policy(IReadOnlyList<FindingRecord> findings) =>
        findings.Count == 0 ? Labels.Allow : findings.Max(f => Rank(f.Severity)) switch
        {
            >= 2 => Labels.Block,
            1 => Labels.Review,
            _ => Labels.Allow,
        };

    private static string Findings(IEnumerable<FindingRecord> findings) =>
        string.Join("; ", findings.Select(f => Invariant($"{f.Code} {f.Severity} {f.Confidence:0.###}")));

    private static string Rate(int successes, int trials)
    {
        if (Confusion.Wilson(successes, trials) is not { } interval)
        {
            return "n/a (n=0)";
        }

        return Invariant($"{(double)successes / trials:0.00} ({successes}/{trials}; 95 % CI {interval.Low:0.00}–{interval.High:0.00})");
    }

    private static string Percent(int part, int whole) => whole == 0 ? "n/a" : Invariant($"{100.0 * part / whole:0} %");

    private static string Number(double? value) => value is { } number ? number.ToString("F0", CultureInfo.InvariantCulture) : "n/a";

    private static string Invariant(FormattableString value) => value.ToString(CultureInfo.InvariantCulture);
